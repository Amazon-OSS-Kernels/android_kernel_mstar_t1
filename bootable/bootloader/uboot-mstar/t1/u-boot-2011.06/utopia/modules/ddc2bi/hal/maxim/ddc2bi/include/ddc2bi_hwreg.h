#define DDC2BI_DVI3_INT_FLAG        0x04a4UL
#define DDC2BI_DVI3_INT_CLR         0x04a7UL
#define DDC2BI_DVI3_WB_RP           0x04a0UL
#define DDC2BI_DVI3_RB_WP           0x04a1UL

#define DDC2BI_DVI_INT_FLAG         0x0412UL
#define DDC2BI_DVI_INT_CLR          0x041EUL
