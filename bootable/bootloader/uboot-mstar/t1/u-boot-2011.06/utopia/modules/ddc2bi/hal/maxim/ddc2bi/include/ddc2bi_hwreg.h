#define DDC2BI_DVI0_INT_MASK        0x0416UL
#define DDC2BI_DVI0_INT_FLAG        0x0412UL
#define DDC2BI_DVI0_INT_CLR         0x041EUL
#define DDC2BI_DVI0_WB_RP           0x0404UL
#define DDC2BI_DVI0_RB_WP           0x0405UL

//DDC2BI for DVI1
#define DDC2BI_DVI1_ID              0x040DUL
#define DDC2BI_DVI1_INT_MASK        0x0417UL
#define DDC2BI_DVI1_INT_FLAG        0x0413UL
#define DDC2BI_DVI1_INT_CLR         0x041FUL
#define DDC2BI_DVI1_WB_RP           0x0406UL
#define DDC2BI_DVI1_RB_WP           0x0407UL

//DDC2BI for DVI2
#define DDC2BI_DVI2_ID              0x0452UL
#define DDC2BI_DVI2_INT_MASK        0x0455UL
#define DDC2BI_DVI2_INT_FLAG        0x0454UL
